"""Generated output must be byte-identical and carry a fixed header."""

import filecmp
import os
import re
import subprocess
import sys
from pathlib import Path

import pytest

from modelgen import __version__

CONTRACT = """\
version: "1.2.3"
kind: DataContract
apiVersion: v3.0.2
id: 11111111-1111-1111-1111-111111111111
status: active
name: user_signed_up
servers:
  - server: landing
    type: bigquery
    project: my-project
    dataset: landing
schema:
  - name: user_signed_up
    physicalName: user_signups_raw
    physicalType: table
    customProperties:
      - property: modelgenLoadedAtField
        value: RECEIVED_AT
      - property: modelgenRaw
        value:
          dataset: raw
          incrementalStrategy: merge
      - property: modelgenStaging
        value:
          dataset: staging
    properties:
      - name: event_id
        physicalName: EVENT_ID
        logicalType: string
        physicalType: STRING
        primaryKey: true
        primaryKeyPosition: 1
        required: true
        unique: true
      - name: received_at
        physicalName: RECEIVED_AT
        logicalType: date
        physicalType: TIMESTAMP
        required: true
"""

_RUNNER = "from modelgen.cli import main; main()"


def generate(contract: Path, out: Path, hashseed: str = "0") -> None:
    env = {
        **os.environ,
        "PYTHONHASHSEED": hashseed,
        "LC_ALL": "C",
    }
    for layer in ("raw", "staging"):
        subprocess.run(
            [
                sys.executable,
                "-c",
                _RUNNER,
                "gen",
                str(contract),
                f"--{layer}",
                "--from-contract",
                "-o",
                str(out / layer),
            ],
            cwd=contract.parent,
            env=env,
            check=True,
            capture_output=True,
        )


def assert_trees_equal(a: Path, b: Path) -> None:
    names_a = sorted(p.relative_to(a).as_posix() for p in a.rglob("*"))
    names_b = sorted(p.relative_to(b).as_posix() for p in b.rglob("*"))
    assert names_a == names_b
    assert any(n.endswith(".sql") for n in names_a)
    for n in names_a:
        if (a / n).is_file():
            assert filecmp.cmp(a / n, b / n, shallow=False), n


def make_contract(root: Path) -> Path:
    root.mkdir(parents=True)
    p = root / "contract.yml"
    p.write_text(CONTRACT)
    return p


def generated_files(out: Path) -> list[Path]:
    return sorted(p for p in out.rglob("*") if p.suffix in (".sql", ".yml"))


def test_output_byte_identical_across_runs(tmp_path):
    contract = make_contract(tmp_path / "src")
    generate(contract, tmp_path / "a", hashseed="0")
    generate(contract, tmp_path / "b", hashseed="1")
    assert_trees_equal(tmp_path / "a", tmp_path / "b")


def test_output_independent_of_checkout_path(tmp_path):
    c1 = make_contract(tmp_path / "one" / "checkout")
    c2 = make_contract(tmp_path / "two" / "deeper" / "elsewhere")
    generate(c1, tmp_path / "out1")
    generate(c2, tmp_path / "out2")
    assert_trees_equal(tmp_path / "out1", tmp_path / "out2")


def test_header_contains_no_timestamp_or_absolute_path(tmp_path):
    contract = make_contract(tmp_path / "src")
    generate(contract, tmp_path / "out")
    files = generated_files(tmp_path / "out")
    assert files
    for f in files:
        text = f.read_text()
        assert str(tmp_path) not in text, f.name
        header = [
            line
            for line in text.splitlines()
            if "GENERATED" in line or "Contract:" in line
        ]
        assert header, f.name
        for line in header:
            assert not re.search(r"\d{4}-\d{2}-\d{2}T", line)
            assert not any(tok.startswith("/") for tok in line.split())


@pytest.mark.parametrize("suffix", [".sql", ".yml"])
def test_header_names_contract_and_version(tmp_path, suffix):
    contract = make_contract(tmp_path / "src")
    generate(contract, tmp_path / "out")
    prefix = "--" if suffix == ".sql" else "#"
    expected = (
        f"{prefix} GENERATED by modelgen {__version__} from"
        " user_signed_up 1.2.3. Do not edit."
    )
    files = [
        f for f in generated_files(tmp_path / "out") if f.suffix == suffix
    ]
    assert len(files) == 2
    for f in files:
        assert f.read_text().splitlines()[0] == expected, f.name
