"""0.14.1 public Python API compatibility and the shared header helper."""

from __future__ import annotations

import warnings

import pytest
from test_modelgen import (
    CONTRACT_YAML,
    SOURCE_DATASET,
    SOURCE_PROJECT,
    SOURCE_TABLE,
    _source_columns,
)

from modelgen.contract import EventContract
from modelgen.generator import (
    Layer,
    generate,
    render_raw,
    render_staging,
)
from modelgen.introspect import FakeIntrospector


@pytest.fixture
def contract() -> EventContract:
    return EventContract.from_text(CONTRACT_YAML)


@pytest.fixture
def introspector() -> FakeIntrospector:
    return FakeIntrospector(
        {(SOURCE_PROJECT, SOURCE_DATASET, SOURCE_TABLE): _source_columns()}
    )


def _no_warning(fn, *a, **kw):
    with warnings.catch_warnings():
        warnings.simplefilter("error")
        return fn(*a, **kw)


def test_render_raw_accepts_contract_path_and_warns(contract, introspector):
    with pytest.warns(DeprecationWarning, match="contract_path"):
        files, _ = render_raw(contract, introspector, "contract.yml")
    assert files == _no_warning(render_raw, contract, introspector)[0]


def test_render_raw_accepts_contract_path_keyword(contract, introspector):
    with pytest.warns(DeprecationWarning, match="contract_path"):
        render_raw(contract, introspector, contract_path="x.yml")


def test_render_staging_accepts_contract_path_and_warns(
    contract, introspector
):
    with pytest.warns(DeprecationWarning, match="contract_path"):
        files, _ = render_staging(contract, introspector, "contract.yml")
    assert files == _no_warning(render_staging, contract, introspector)[0]


def test_generate_old_positional_call_works_and_warns(
    contract, introspector, tmp_path
):
    with pytest.warns(DeprecationWarning, match="contract_path"):
        res = generate(
            contract, introspector, tmp_path, Layer.RAW, "contract.yml", True
        )
    assert res.written
    assert not any(tmp_path.iterdir())  # 6th positional is dry_run


def test_generate_keyword_contract_path_warns(
    contract, introspector, tmp_path
):
    with pytest.warns(DeprecationWarning, match="contract_path"):
        generate(
            contract,
            introspector,
            tmp_path,
            Layer.STAGING,
            contract_path="c.yml",
            dry_run=True,
        )


def test_no_warning_without_contract_path(contract, introspector, tmp_path):
    _no_warning(generate, contract, introspector, tmp_path, Layer.RAW)
    _no_warning(
        generate, contract, introspector, tmp_path, Layer.RAW, dry_run=True
    )
    _no_warning(generate, contract, introspector, tmp_path, Layer.RAW, None)


def test_provenance_header_with_version():
    from modelgen.generator import provenance_header

    h = provenance_header("c", "1.2.3")
    assert h.startswith("GENERATED by modelgen ")
    assert h.endswith(" from c 1.2.3. Do not edit.")


@pytest.mark.parametrize("missing", ["", None])
def test_provenance_header_without_version_has_no_stray_space(missing):
    from modelgen.generator import provenance_header

    h = provenance_header("c", missing)
    assert h.endswith(" from c. Do not edit.")
    assert " ." not in h
