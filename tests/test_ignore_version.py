"""`check --ignore-version`: a release alone does not count as drift."""

import os
import subprocess
import sys
from pathlib import Path

import pytest

from modelgen import __version__

HERE = Path(__file__).parent
EXAMPLE = HERE.parent / "contracts" / "example_contract.yml"
_RUNNER = "from modelgen.cli import main; main()"
STAMP = f"GENERATED by modelgen {__version__} from"
OLD_STAMP = "GENERATED by modelgen 0.0.1 from"


def _cli(*args: str, cwd: Path):
    env = {**os.environ, "PYTHONHASHSEED": "0", "LC_ALL": "C"}
    return subprocess.run(
        [sys.executable, "-c", _RUNNER, *args],
        cwd=cwd,
        env=env,
        capture_output=True,
        text=True,
    )


@pytest.fixture
def project(tmp_path: Path) -> Path:
    (tmp_path / "contracts").mkdir()
    (tmp_path / "contracts" / "c.yml").write_text(EXAMPLE.read_text())
    (tmp_path / ".modelgen.yml").write_text(
        "contracts: contracts/*.yml\n"
        "raw_output: models/raw\n"
        "staging_output: models/staging\n"
    )
    assert _cli("run", cwd=tmp_path).returncode == 0
    return tmp_path


def _restamp(path: Path, extra: str = "") -> None:
    text = path.read_text()
    assert STAMP in text.splitlines()[0]
    path.write_text(text.replace(STAMP, OLD_STAMP, 1) + extra)


@pytest.mark.parametrize("suffix", [".sql", ".yml"])
def test_version_only_difference_passes_with_flag(project, suffix):
    _restamp(project / "models" / "raw" / f"raw__user_signed_up{suffix}")
    assert _cli("check", cwd=project).returncode == 4
    assert _cli("check", "--ignore-version", cwd=project).returncode == 0


def test_any_other_difference_still_drifts_with_flag(project):
    _restamp(
        project / "models" / "staging" / "stg__user_signed_up.sql", "-- x\n"
    )
    assert _cli("check", "--ignore-version", cwd=project).returncode == 4
